#!/usr/bin/env python3
"""Generate a TAP spec from openfga/language's DSL semantic validation cases, and report results.

    python3 -I test/fga_lang/generate.py                  # write test/spec/d/62_fga_lang_oracle.sql, print counts
    test/run.sh -v fga_lang_oracle > /tmp/lang.out
    python3 -I test/fga_lang/generate.py report /tmp/lang.out   # counts: run, passed, failed, skipped by reason

Input: test/fga_lang/cases.json (written by vendor.sh: one upstream case per
line, with its DSL model converted to JSON and OpenFGA's server's answer to
writing it) and test/fga_lang/skip.tsv.

Each case is one TAP test named lang:<index>:<name>. A case with no
expected_errors must be accepted by fga_write_authorization_model; a case with
expected_errors must be rejected with the OpenFGA error code the server gives
for that JSON (cases.json, field server) and a non-empty HINT. The upstream
messages are the language library's, not the server's, so they are not
matched. Cases are run whatever upstream's own `skip` flag says unless
skip.tsv lists them; the generator refuses a case whose expectation the server
contradicts unless skip.tsv lists it. Expectations are never edited.
"""
import json
import os
import re
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))          # pg_permissions/
SPEC = os.path.join(ROOT, 'test', 'spec', 'd', '62_fga_lang_oracle.sql')

# OpenFGA's error code names (openfga/api openfga/v1/errors_ignore.proto) for
# the codes the server returns in cases.json.
CODES = {
    'validation_error': 2000,
    'type_invalid_pattern': 2047,
    'relations_invalid_pattern': 2050,
    'invalid_authorization_model': 2056,
}


def load_cases():
    with open(os.path.join(HERE, 'cases.json')) as f:
        cases = [json.loads(line) for line in f if line.strip()]
    for i, c in enumerate(cases):
        c['index'] = i
    return cases


def load_skips():
    skips = {}
    with open(os.path.join(HERE, 'skip.tsv')) as f:
        for line in f:
            if not line.strip() or line.startswith('#'):
                continue
            case, reason, note = (line.rstrip('\n').split('\t') + ['', ''])[:3]
            if case in skips:
                sys.exit(f'skip.tsv: {case!r} listed twice')
            skips[case] = (reason, note)
    return skips


def lit(v):
    return "'" + str(v).replace("'", "''") + "'"


def expects_rejection(case):
    return bool(case.get('expected_errors'))


def expected_code(case):
    """None if the model must be accepted, else the server's numeric code."""
    if not expects_rejection(case):
        return None
    code = case['server']['code']
    if code not in CODES:
        sys.exit(f"case {case['index']} {case['name']!r}: unknown server code {code!r}; add it to CODES")
    return CODES[code]


def test_name(case):
    return f"lang:{case['index']}:{case['name']}"


def generate():
    cases = load_cases()
    skips = load_skips()
    unknown = set(skips) - {c['name'] for c in cases}
    if unknown:
        sys.exit(f'skip.tsv names unknown cases: {sorted(unknown)}')

    body, skipped, by_reason = [], [], Counter()
    run_upstream_skip = []
    for c in cases:
        if c['name'] in skips:
            reason, note = skips[c['name']]
            by_reason[reason] += 1
            skipped.append(f"\\echo '# SKIP {c['index']} {c['name'].replace(chr(39), '')}: {reason}'")
            continue
        if c.get('model_json') is None:
            sys.exit(f"case {c['index']} {c['name']!r}: the transformer refused it; list it in skip.tsv")
        server_rejects = c['server']['http'] >= 400
        if server_rejects != expects_rejection(c):
            sys.exit(f"case {c['index']} {c['name']!r}: expects {'rejection' if expects_rejection(c) else 'acceptance'}, "
                     f"server answered {c['server']['http']} {c['server']['code']}; list it in skip.tsv")
        if c.get('skip'):
            run_upstream_skip.append(c)
        code = expected_code(c)
        model = json.dumps(c['model_json'], separators=(',', ':'), sort_keys=True)
        body.append(f"-- {c['index']}: {c['name']}"
                    + (f" (upstream skip: true; the server agrees with the expectation)" if c.get('skip') else ''))
        body.append(f"select tap.is(fga_test.model_write({lit(model)}::jsonb, {'null' if code is None else code}), "
                    f"'ok', {lit(test_name(c))});")

    with open(SPEC, 'w') as f:
        f.write("-- Generated by test/fga_lang/generate.py from test/fga_lang/cases.json. Do not edit.\n")
        f.write("-- openfga/language dsl-semantic-validation-cases.yaml, Apache-2.0: see test/fga_lang/upstream/SOURCE.\n")
        f.write("-- Each case: fga_write_authorization_model accepts the model, or rejects it with the\n")
        f.write("-- OpenFGA code the server gives and a HINT (fga_test.model_write).\n")
        f.write("\\set ON_ERROR_STOP off\n\\ir ../../fixtures/fga_suite.sql\n")
        f.write('\n'.join(skipped) + '\n')
        f.write(f"select tap.plan({len(body) // 2});\n")
        f.write('\n'.join(body) + '\n')
        f.write("\nselect * from tap.finish();\n")

    n_run = len(body) // 2
    accept = sum(1 for c in cases if c['name'] not in skips and not expects_rejection(c))
    codes = Counter(expected_code(c) for c in cases if c['name'] not in skips and expects_rejection(c))
    print(f'upstream: {len(cases)} cases ({sum(1 for c in cases if c.get("skip"))} marked skip: true upstream)')
    print(f'run: {n_run} cases ({accept} must be accepted, {n_run - accept} rejected: '
          + ', '.join(f'{k}: {v}' for k, v in sorted(codes.items())) + ')')
    print(f'skipped: {sum(by_reason.values())} cases')
    for r in sorted(by_reason):
        print(f'    skipped {r}: {by_reason[r]}')
    if run_upstream_skip:
        print(f'run although upstream marks skip: true (the server agrees with the expectation): '
              + ', '.join(str(c['index']) for c in run_upstream_skip))


def report(path):
    cases = load_cases()
    skips = load_skips()
    pat = re.compile(r'^\s*(ok|not ok) \d+ - lang:(\d+):')
    got = {}
    with open(path) as f:
        for line in f:
            line = re.sub(r'\x1b\[[0-9;]*m', '', line)
            m = pat.match(line)
            if m:
                got[int(m.group(2))] = m.group(1) == 'ok'
    expected = [c['index'] for c in cases if c['name'] not in skips]
    passed = [i for i in expected if got.get(i)]
    failed = [i for i in expected if got.get(i) is False]
    missing = [i for i in expected if i not in got]
    by_reason = Counter(skips[c['name']][0] for c in cases if c['name'] in skips)
    print(f'cases {len(cases)}: run {len(expected)}, passed {len(passed)}, failed {len(failed)}, not run {len(missing)}; '
          f'skipped {sum(by_reason.values())} (' + ', '.join(f'{r}: {by_reason[r]}' for r in sorted(by_reason)) + ')')
    for i in failed + missing:
        print(f'    {"failed" if i in failed else "not run"}: {i} {cases[i]["name"]}')


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'report':
        report(sys.argv[2])
    else:
        generate()
