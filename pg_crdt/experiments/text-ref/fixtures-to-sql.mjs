// Emits fixtures/fixtures.sql from fixtures/*.json. Usage: node fixtures-to-sql.mjs
// Load with: psql -f fixtures/fixtures.sql  (client_encoding must be UTF8). Drops and recreates text_fixtures.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), 'fixtures');
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();

// Dollar-quote with a tag that does not occur in the data. No escaping needed then.
function lit(s) {
  let tag = 'fx';
  while (s.includes(`$${tag}$`) || s.endsWith(`$${tag}`)) tag += 'x';
  return `$${tag}$${s}$${tag}$`;
}

let sql = '-- generated by fixtures-to-sql.mjs; do not edit\n';
sql += 'drop table if exists text_fixtures;\n';
sql += 'create table text_fixtures(name text primary key, ops jsonb, ops_causal jsonb, expected text);\n';
for (const f of files) {
  const j = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  sql += `insert into text_fixtures(name, ops, ops_causal, expected) values (${lit(f.replace(/\.json$/, ''))}, ` +
    `${lit(JSON.stringify(j.ops))}::jsonb, ${lit(JSON.stringify(j.ops_causal))}::jsonb, ${lit(j.expected)});\n`;
}
writeFileSync(join(dir, 'fixtures.sql'), sql);
console.log(`wrote fixtures/fixtures.sql (${files.length} fixtures, ${sql.length} chars)`);
