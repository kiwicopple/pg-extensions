#!/usr/bin/env node
// Sync the pg_crdt docs into the Starlight site.
//
//   npm run sync     (also runs automatically before `npm run dev` and `npm run build`)
//
// Everything this script writes is generated and gitignored; edit the sources in .. (pg_crdt/).
//   1. Markdown   -> src/content/docs/<route>.md  (frontmatter added, relative links rewritten;
//                    the page inventory and sidebar are in navigation.mjs).
//                    A page with code tab groups is written as <route>.mdx instead (see convertTabs).
//   2. Plain Markdown exports -> public/markdown/<route>.md, and an index in public/llms.txt.
//
// Research records (../research) are not part of this site. Links to them become absolute URLs on the
// research site (research-site/ at the repo root, see research-links.mjs).
//
// Adapted from pg_validate/site/scripts/sync.mjs, with the code tabs of pg_permissions/site/scripts.
//
// Hand-written pages are .mdx; generated pages are .md, or .mdx with the GENERATED marker on its first
// line after the imports. rmGenerated removes only those, so cleaning is safe.

import fs from 'node:fs';
import { pages } from '../navigation.mjs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { convertTabs } from './code-tabs.mjs';
import { RESEARCH_URL, researchSourceUrl } from '../research-links.mjs';

const DOCS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_ROOT = path.resolve(DOCS, '..'); // pg_crdt/ (this site is pg_crdt/site)
const OUT_DOCS = path.join(DOCS, 'src', 'content', 'docs');
const REPO = process.env.DOCS_REPO_URL ?? 'https://github.com/kiwicopple/pg-extensions';
const REF = process.env.DOCS_REPO_REF ?? 'main';
const REPO_PREFIX = 'pg_crdt'; // where SRC_ROOT lives inside the repo

/**
 * source file (relative to pg_crdt) -> route (no leading or trailing slash) and sidebar label.
 * navigation.mjs defines both the page inventory and sidebar.
 * A page whose source file is missing is skipped with a warning; links to a skipped page render as plain code.
 */
const PAGES = pages;

/** Directories (and a few files) that have a better home on the site than GitHub. */
const DIR_ROUTES = {
	docs: 'guide',
	test: 'contributing/test-suite',
	'test/README.md': 'contributing/test-suite',
};

const warnings = [];
const warn = (m) => {
	if (warnings.includes(m)) return; // the same dead link repeated in one page is one warning
	warnings.push(m);
	console.warn(`sync: warning: ${m}`);
};

const MDX_MARKER = 'GENERATED by pg_crdt/site/scripts/sync.mjs';

const posix = (p) => p.split(path.sep).join('/');

// Pages that exist. Links are only rewritten to these, so a link to a page that isn't written yet
// falls through to the "target not found" branch and doesn't become a dead link in the build.
const AVAILABLE = PAGES.filter((p) => {
	if (fs.existsSync(path.join(SRC_ROOT, p.src))) return true;
	warn(`source missing, skipped: ${p.src}`);
	return false;
});
const bySrc = new Map(AVAILABLE.map((p) => [p.src, p]));

function rmGenerated(dir) {
	if (!fs.existsSync(dir)) return;
	for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) {
			rmGenerated(p);
			if (!fs.readdirSync(p).length) fs.rmdirSync(p);
		} else if (e.name.endsWith('.md')) fs.rmSync(p);
		else if (e.name.endsWith('.mdx') && fs.readFileSync(p, 'utf8').includes(MDX_MARKER)) fs.rmSync(p); // generated, not hand-written
	}
}

/** Relative URL between two routes, e.g. designs/a -> decision/guide gives ../../decision/guide/. */
function routeLink(fromRoute, toRoute) {
	const up = fromRoute.split('/').length;
	return '../'.repeat(up) + toRoute + '/';
}

function githubUrl(relToRoot, isDir) {
	const p = [REPO_PREFIX, relToRoot].filter(Boolean).join('/').replace(/\/+$/, '');
	return `${REPO}/${isDir ? 'tree' : 'blob'}/${REF}/${p}${isDir ? '' : ''}`;
}

/** Rewrite one link target found in `srcFile`. Returns {url} or {code} (render as plain code). */
function rewriteTarget(target, srcFile, fromRoute, markdown = false) {
	if (/^([a-z][a-z0-9+.-]*:|\/\/)/i.test(target) || target.startsWith('#')) return { url: target };
	const m = target.match(/^([^#?]*)([?#].*)?$/);
	const pathPart = m[1];
	const tail = m[2] ?? '';
	const abs = path.resolve(SRC_ROOT, path.dirname(srcFile), decodeURI(pathPart));
	const rel = posix(path.relative(SRC_ROOT, abs));
	if (rel.startsWith('..')) return { code: target };
	if (bySrc.has(rel)) {
		const route = bySrc.get(rel).route;
		const url = markdown ? path.posix.relative(path.posix.dirname(fromRoute), route + '.md') : routeLink(fromRoute, route);
		return { url: url + tail.replace(/^\?[^#]*/, '') };
	}
	const research = researchSourceUrl(rel, tail.replace(/^\?[^#]*/, ''));
	if (research) return { url: research };
	const key = rel.replace(/\/$/, '');
	if (DIR_ROUTES[key]) {
		const route = DIR_ROUTES[key];
		return { url: (markdown ? path.posix.relative(path.posix.dirname(fromRoute), route + '.md') : routeLink(fromRoute, route)) + tail };
	}
	if (!fs.existsSync(abs)) {
		warn(`${srcFile}: link target not found: ${target}`);
		return { code: target };
	}
	const isDir = fs.statSync(abs).isDirectory();
	return { url: githubUrl(rel, isDir) + (isDir ? '' : tail) };
}

/** Rewrite links in markdown, leaving fenced code blocks and inline code untouched. */
function rewriteLinks(body, srcFile, fromRoute, markdown = false) {
	const lines = body.split('\n');
	let fence = null;
	return lines
		.map((line) => {
			const f = line.match(/^\s*(`{3,}|~{3,})/);
			if (f) {
				if (!fence) fence = f[1][0].repeat(f[1].length);
				else if (f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
				return line;
			}
			if (fence) return line;
			// inline code spans are matched first so their contents are never rewritten;
			// link text may itself contain code spans.
			const re = /(`+[^`]*`+)|(!?)\[((?:[^\]`]|`[^`]*`)*)\]\(([^)\s]+)(\s+"[^"]*")?\)/g;
			line = line.replace(re, (all, code, bang, text, target, title) => {
				if (code) return all;
				const r = rewriteTarget(target, srcFile, fromRoute, markdown);
				if (r.code) return bang ? all : `${text} (\`${r.code}\`)`;
				return `${bang}[${text}](${r.url}${title ?? ''})`;
			});
			return line.replace(/^(\s*\[[^\]]+\]:\s*)(\S+)/, (all, pre, target) => {
				const r = rewriteTarget(target, srcFile, fromRoute, markdown);
				return r.url ? pre + r.url : all;
			});
		})
		.join('\n');
}

/**
 * Escape what MDX reads as code or markup, in prose only: a brace starts an expression and a `<` starts a tag.
 * Fenced code and inline code spans are left alone.
 */
function escapeMdx(body) {
	let fence = null;
	return body
		.split('\n')
		.map((line) => {
			const f = line.match(/^\s*(`{3,}|~{3,})/);
			if (f) {
				if (!fence) fence = f[1][0].repeat(f[1].length);
				else if (f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
				return line;
			}
			if (fence || /^\s*<\/?(Tabs|TabItem)\b/.test(line)) return line;
			return line
				.split(/(`+[^`]*`+)/)
				.map((part, i) => (i % 2 ? part : part.replace(/[{}<]/g, (c) => '\\' + c)))
				.join('');
		})
		.join('\n');
}

function stripInline(s) {
	return s
		.replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/`/g, '')
		.replace(/\*\*/g, '')
		.replace(/\s+/g, ' ')
		.trim();
}

function firstParagraph(body) {
	const paras = body.split(/\n\s*\n/);
	for (const p of paras) {
		const t = p.trim();
		if (!t || /^(#|```|~~~|\||[-*]\s|\d+\.\s|>|<)/.test(t)) continue;
		let s = stripInline(t);
		if (s.length > 180) s = s.slice(0, 177).replace(/\s+\S*$/, '') + '...';
		return s;
	}
	return '';
}

const yaml = (s) => JSON.stringify(s);

function syncMarkdown() {
	rmGenerated(OUT_DOCS);
	let n = 0;
	let nMdx = 0;
	for (const page of AVAILABLE) {
		const file = path.join(SRC_ROOT, page.src);
		let text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
		const h1 = text.match(/^# (.+)\n/m);
		let title = page.label;
		if (h1) {
			title = stripInline(h1[1]);
			text = text.replace(h1[0], ''); // Starlight renders the title as the page H1
		}
		const description = firstParagraph(text);
		let body = rewriteLinks(text, page.src, page.route);
		const tabs = convertTabs(body, page.src);
		const mdx = tabs.groups > 0;
		if (mdx) body = escapeMdx(tabs.body);
		else body = tabs.body;
		const front = [
			'---',
			`title: ${yaml(title)}`,
			description ? `description: ${yaml(description)}` : null,
			page.legacy ? 'pagefind: false' : null,
			`editUrl: ${yaml(`${REPO}/edit/${REF}/${REPO_PREFIX}/${page.src}`)}`,
			`sidebar:\n  label: ${yaml(page.label)}${page.order ? `\n  order: ${page.order}` : ''}`,
			'---',
		]
			.filter(Boolean)
			.join('\n');
		const note = `${MDX_MARKER} from pg_crdt/${page.src}. Do not edit.`;
		const out = mdx
			? `${front}\n\nimport { Tabs, TabItem } from '@astrojs/starlight/components';\n\n{/* ${note} */}\n\n${body.replace(/^\n+/, '')}`
			: `${front}\n\n<!-- ${note} -->\n\n${body.replace(/^\n+/, '')}`;
		const dest = path.join(OUT_DOCS, page.route + (mdx ? '.mdx' : '.md'));
		fs.mkdirSync(path.dirname(dest), { recursive: true });
		fs.writeFileSync(dest, out);
		n++;
		if (mdx) {
			nMdx++;
			console.log(`sync: ${page.route}: ${tabs.groups} tab group(s), written as .mdx`);
		}
	}
	console.log(`sync: ${n}/${PAGES.length} markdown pages -> src/content/docs (${nMdx} as .mdx)`);
}


function syncPlainMarkdown() {
	const publicDir = path.join(DOCS, 'public');
	const markdownDir = path.join(publicDir, 'markdown');
	fs.rmSync(markdownDir, { recursive: true, force: true });
	const base = (process.env.DOCS_BASE ?? '').replace(/\/$/, '');
	const site = (process.env.DOCS_SITE ?? '').replace(/\/$/, '');
	const index = [
		'# pg_crdt', '',
		'> CRDTs (conflict-free replicated data types) for Postgres, in SQL and PL/pgSQL. Version 0.0.1 has one type, the PN-Counter, a counter that several writers can change independently and merge later.', '',
		'Use the guides and reference for implementation. Only the PN-Counter exists; the other types on the overview page are planned. Guides show JavaScript (node-postgres) examples first and the equivalent SQL. Markdown exports preserve every language example.', '',
		'## Guides and reference', '',
	];
	const groups = { current: [], contributing: [] };
	for (const page of AVAILABLE) {
		const text = fs.readFileSync(path.join(SRC_ROOT, page.src), 'utf8');
		const dest = path.join(markdownDir, page.route + '.md');
		fs.mkdirSync(path.dirname(dest), { recursive: true });
		const body = rewriteLinks(text, page.src, page.route, true);
		fs.writeFileSync(dest, body);
		if (page.legacy) continue;
		const description = firstParagraph(text);
		const title = stripInline(text.match(/^# (.+)$/m)?.[1] ?? page.label);
		const group = page.route.startsWith('contributing/') ? 'contributing' : 'current';
		groups[group].push(`- [${title}](${site}${base}/markdown/${page.route}.md): ${description}`);
	}
	index.push(...groups.current, '', '## Research and design records', '',
		`- [Research and design records](${RESEARCH_URL}/): The architecture, prior art, benchmarks and the build journal, on the separate research site.`,
		'', '## Contributing', '', ...groups.contributing);
	fs.writeFileSync(path.join(publicDir, 'llms.txt'), index.join('\n') + '\n');
	console.log(`sync: ${AVAILABLE.length} plain Markdown exports and llms.txt`);
}

if (!fs.existsSync(SRC_ROOT)) {
	console.error(`sync: ${SRC_ROOT} not found`);
	process.exit(1);
}
syncMarkdown();
syncPlainMarkdown();
if (warnings.length) console.warn(`sync: ${warnings.length} warning(s)`);
