#!/usr/bin/env node
// Sync every <extension>/research/ directory into the Starlight site.
//
//   npm run sync     (also runs automatically before `npm run dev` and `npm run build`)
//
// Everything this script writes is generated and gitignored; edit the sources in <extension>/research/.
//   1. Markdown -> src/content/docs/<extension>/<route>.md (frontmatter added, relative links rewritten).
//                  The pages and routes come from research/navigation.json, or from the directory tree
//                  when an extension has none (see site.mjs). README.md is the extension's index.
//   2. Landing  -> src/content/docs/index.md, one entry per extension.
//   3. Extension data: src/extensions/<extension>/sync.mjs, when it exists, is called with the extension
//      directory (pg_permissions copies its benchmark data for the chart pages).
//
// Links: to another research page -> relative site link; to <extension>/docs/ -> the extension's user site
// (navigation.json's userSite, routes from <extension>/site/navigation.mjs); to any other repository file
// -> GitHub. Hand-written pages are .mdx and are never removed. Adapted from pg_permissions/site/scripts/sync.mjs.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { REF, REPO, REPO_ROOT, SITE_DIR, extensions, slug } from '../site.mjs';

const OUT_DOCS = path.join(SITE_DIR, 'src', 'content', 'docs');
const MARKER = 'GENERATED by research-site/scripts/sync.mjs';

const warnings = [];
const warn = (m) => {
	if (warnings.includes(m)) return; // the same dead link repeated in one page is one warning
	warnings.push(m);
	console.warn(`sync: warning: ${m}`);
};

const posix = (p) => p.split(path.sep).join('/');
const yaml = (s) => JSON.stringify(s);

const EXTENSIONS = extensions();

// Every page of every extension, keyed by its repository path, e.g. pg_permissions/research/journal.md.
const PAGES = EXTENSIONS.flatMap((e) =>
	e.pages
		.map((p) => ({ ...p, ext: e.name, file: `${e.name}/research/${p.src}`, slug: slug(e.name, p.route) }))
		.filter((p) => {
			if (fs.existsSync(path.join(REPO_ROOT, p.file))) return true;
			warn(`source missing, skipped: ${p.file}`);
			return false;
		}),
);
const byFile = new Map(PAGES.map((p) => [p.file, p]));

// Hand-written pages (src/content/docs/**/*.mdx) are link targets too, by their path in the repository.
const walkFiles = (d) =>
	fs.existsSync(d)
		? fs.readdirSync(d, { withFileTypes: true }).flatMap((x) => (x.isDirectory() ? walkFiles(path.join(d, x.name)) : [path.join(d, x.name)]))
		: [];
for (const f of walkFiles(OUT_DOCS).filter((x) => x.endsWith('.mdx') && !fs.readFileSync(x, 'utf8').includes(MARKER))) {
	const rel = posix(path.relative(OUT_DOCS, f)).replace(/\.mdx$/, '');
	byFile.set(posix(path.relative(REPO_ROOT, f)), { slug: rel.replace(/(^|\/)index$/, '') });
}

// Markdown in a research directory that navigation.json leaves out stays on GitHub only.
for (const e of EXTENSIONS.filter((x) => x.nav)) {
	for (const f of walkFiles(path.join(REPO_ROOT, e.name, 'research')).filter((x) => x.endsWith('.md'))) {
		const rel = posix(path.relative(REPO_ROOT, f));
		if (!byFile.has(rel)) warn(`not in ${e.name}/research/navigation.json, links go to GitHub: ${rel}`);
	}
}

// User site routes, from <extension>/site/navigation.mjs (its `pages`: { src, route } relative to the extension).
const userRoutes = new Map();
for (const e of EXTENSIONS.filter((x) => x.nav?.userSite)) {
	const navFile = path.join(REPO_ROOT, e.name, 'site', 'navigation.mjs');
	if (!fs.existsSync(navFile)) continue;
	const { pages = [] } = await import(pathToFileURL(navFile).href);
	const site = e.nav.userSite.replace(/\/+$/, '');
	for (const p of pages) userRoutes.set(`${e.name}/${p.src}`, `${site}/${p.route}/`);
	const readme = pages.find((p) => p.src === 'docs/README.md');
	if (readme) userRoutes.set(`${e.name}/docs`, `${site}/${readme.route}/`);
}

function rmGenerated(dir) {
	if (!fs.existsSync(dir)) return;
	for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) {
			rmGenerated(p);
			if (!fs.readdirSync(p).length) fs.rmdirSync(p);
		} else if (e.name.endsWith('.md')) fs.rmSync(p);
		else if (e.name.endsWith('.mdx') && fs.readFileSync(p, 'utf8').includes(MARKER)) fs.rmSync(p);
	}
}

/** Relative URL between two slugs, e.g. pg_permissions/designs/a -> pg_permissions/decision gives ../../decision/. */
function slugLink(from, to) {
	const up = from ? from.split('/').length : 0;
	return '../'.repeat(up) + (to ? to + '/' : '');
}

function githubUrl(rel, isDir) {
	return `${REPO}/${isDir ? 'tree' : 'blob'}/${REF}/${rel.replace(/\/+$/, '')}`;
}

/** Rewrite one link target found in page `page`. Returns {url} or {code} (render as plain code). */
function rewriteTarget(target, page) {
	if (/^([a-z][a-z0-9+.-]*:|\/\/)/i.test(target) || target.startsWith('#')) return { url: target };
	const m = target.match(/^([^#?]*)([?#].*)?$/);
	const tail = m[2] ?? '';
	const abs = path.resolve(REPO_ROOT, path.dirname(page.file), decodeURI(m[1]));
	const rel = posix(path.relative(REPO_ROOT, abs));
	if (rel.startsWith('..')) return { code: target };
	const key = rel.replace(/\/$/, '');
	const hit = byFile.get(key) ?? byFile.get(`${key}/README.md`); // a directory links to its README page
	if (hit) return { url: slugLink(page.slug, hit.slug) + tail.replace(/^\?[^#]*/, '') };
	if (userRoutes.has(key)) return { url: userRoutes.get(key) + tail.replace(/^\?[^#]*/, '') };
	if (!fs.existsSync(abs)) {
		warn(`${page.file}: link target not found: ${target}`);
		return { code: target };
	}
	const isDir = fs.statSync(abs).isDirectory();
	return { url: githubUrl(rel, isDir) + (isDir ? '' : tail) };
}

/** Rewrite links in markdown, leaving fenced code blocks and inline code untouched. */
function rewriteLinks(body, page) {
	let fence = null;
	return body
		.split('\n')
		.map((line) => {
			const f = line.match(/^\s*(`{3,}|~{3,})/);
			if (f) {
				if (!fence) fence = f[1][0].repeat(f[1].length);
				else if (f[1][0] === fence[0] && f[1].length >= fence.length) fence = null;
				return line;
			}
			if (fence) return line;
			// inline code spans are matched first so their contents are never rewritten;
			// link text may itself contain code spans.
			const re = /(`+[^`]*`+)|(!?)\[((?:[^\]`]|`[^`]*`)*)\]\(([^)\s]+)(\s+"[^"]*")?\)/g;
			line = line.replace(re, (all, code, bang, text, target, title) => {
				if (code) return all;
				const r = rewriteTarget(target, page);
				if (r.code) return bang ? all : `${text} (\`${r.code}\`)`;
				return `${bang}[${text}](${r.url}${title ?? ''})`;
			});
			return line.replace(/^(\s*\[[^\]]+\]:\s*)(\S+)/, (all, pre, target) => {
				const r = rewriteTarget(target, page);
				return r.url ? pre + r.url : all;
			});
		})
		.join('\n');
}

function stripInline(s) {
	return s
		.replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/`/g, '')
		.replace(/\*\*/g, '')
		.replace(/\s+/g, ' ')
		.trim();
}

function firstParagraph(body) {
	for (const p of body.split(/\n\s*\n/)) {
		const t = p.trim();
		if (!t || /^(#|```|~~~|\||[-*]\s|\d+\.\s|>|<)/.test(t)) continue;
		let s = stripInline(t);
		if (s.length > 180) s = s.slice(0, 177).replace(/\s+\S*$/, '') + '...';
		return s;
	}
	return '';
}

function frontmatter(fields) {
	return ['---', ...fields.filter(Boolean), '---'].join('\n');
}

function syncMarkdown() {
	let n = 0;
	for (const page of PAGES) {
		let text = fs.readFileSync(path.join(REPO_ROOT, page.file), 'utf8').replace(/\r\n/g, '\n');
		const h1 = text.match(/^# (.+)\n/m);
		let title = page.label;
		if (h1) {
			title = stripInline(h1[1]);
			text = text.replace(h1[0], ''); // Starlight renders the title as the page H1
		}
		if (page.historical) title = `Historical: ${title}`;
		const description = firstParagraph(text);
		const body = rewriteLinks(text, page);
		const front = frontmatter([
			`title: ${yaml(title)}`,
			description ? `description: ${yaml(description)}` : null,
			`editUrl: ${yaml(`${REPO}/edit/${REF}/${page.file}`)}`,
			`sidebar:\n  label: ${yaml(page.label)}`,
		]);
		const dest = path.join(OUT_DOCS, page.route ? `${page.slug}.md` : path.join(page.ext, 'index.md'));
		if (fs.existsSync(dest.replace(/\.md$/, '.mdx'))) throw new Error(`sync: ${page.file} and a hand-written page both use ${page.slug}`);
		fs.mkdirSync(path.dirname(dest), { recursive: true });
		fs.writeFileSync(dest, `${front}\n\n<!-- ${MARKER} from ${page.file}. Do not edit. -->\n\n${body.replace(/^\n+/, '')}`);
		n++;
	}
	console.log(`sync: ${n} research pages from ${EXTENSIONS.length} extension(s) -> src/content/docs`);
}

function syncLanding() {
	const items = EXTENSIONS.map((e) => {
		const index = PAGES.find((p) => p.ext === e.name && p.route === '');
		const link = index ? slugLink('', e.name) : `${githubUrl(`${e.name}/research`, true)}`;
		const description = index ? firstParagraph(fs.readFileSync(path.join(REPO_ROOT, index.file), 'utf8').replace(/^# .+\n/m, '')) : '';
		const userSite = e.nav?.userSite ? ` User documentation: [${e.nav.userSite.replace(/^https?:\/\//, '')}](${e.nav.userSite}).` : '';
		return `- **[${e.title}](${link})**${description ? `: ${description}` : ''}${userSite}`;
	});
	const front = frontmatter([`title: "Research"`, 'description: "Design records, benchmark reports, reviews and build journals for the extensions in pg-extensions."', 'editUrl: false']);
	const body = [
		'These are the development records of the Postgres extensions in [kiwicopple/pg-extensions](' + REPO + '): designs, benchmark reports, reviews and build journals. Some are historical and describe approaches that were later replaced. For installing and using an extension, read its user documentation.',
		'',
		'## Extensions',
		'',
		...items,
		'',
		`Each section is built from the extension's \`research/\` directory. See [research-site/README.md](${githubUrl('research-site/README.md', false)}) to add one.`,
	];
	fs.writeFileSync(path.join(OUT_DOCS, 'index.md'), `${front}\n\n<!-- ${MARKER}. Do not edit. -->\n\n${body.join('\n')}\n`);
}

async function syncExtensionData() {
	for (const e of EXTENSIONS) {
		const hook = path.join(SITE_DIR, 'src', 'extensions', e.name, 'sync.mjs');
		if (!fs.existsSync(hook)) continue;
		const { default: run } = await import(pathToFileURL(hook).href);
		await run({ extDir: path.join(REPO_ROOT, e.name), warn });
	}
}

rmGenerated(OUT_DOCS);
fs.mkdirSync(OUT_DOCS, { recursive: true });
syncMarkdown();
syncLanding();
await syncExtensionData();
if (warnings.length) console.warn(`sync: ${warnings.length} warning(s)`);
