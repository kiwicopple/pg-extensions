#!/usr/bin/env python3
"""Generate the JSON Schema Test Suite specs from upstream/ and skip.tsv.

    test/json_schema/generate.py

Writes test/spec/40_json_schema_suite.sql (the required tests),
41_json_schema_suite_optional.sql (optional/*.json) and
42_json_schema_suite_format.sql (optional/format/*.json). Each spec loads the
cases into temp tables and runs them with run_suite.sql: one assertion per
case, skipped cases as "SKIP" passes, and a per-file summary as "#" lines.

skip.tsv lists the cases that are not run, with the reason (tab-separated:
file, group description, test description or *, reason). Cases whose JSON
Postgres cannot store (U+0000, lone surrogates) are skipped automatically.
Never edit an expectation; skip with a reason instead.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
SUITE = HERE / 'upstream' / 'tests' / 'draft2020-12'
SPEC = HERE.parent / 'spec'
SOURCE = (HERE / 'upstream' / 'SOURCE').read_text().split('\n')[1].split()[-1]
TAG = '$jsts$'

SPECS = [
    ('40_json_schema_suite.sql', '', 'the required Draft 2020-12 tests'),
    ('41_json_schema_suite_optional.sql', 'optional/', 'the optional Draft 2020-12 tests (not format)'),
    ('42_json_schema_suite_format.sql', 'optional/format/', 'the optional format tests, with format assertion'),
]


def load_skips():
    skips = {}
    for n, line in enumerate((HERE / 'skip.tsv').read_text().split('\n'), 1):
        if not line.strip() or line.startswith('#'):
            continue
        parts = line.split('\t')
        if len(parts) != 4:
            sys.exit(f'skip.tsv:{n}: expected 4 tab-separated fields, got {len(parts)}')
        skips[tuple(parts[:3])] = [parts[3], 0]
    return skips


def unstorable(value):
    """True if jsonb cannot hold the value (U+0000 or an unpaired surrogate)."""
    if isinstance(value, str):
        return any(c == '\x00' or 0xD800 <= ord(c) <= 0xDFFF for c in value)
    if isinstance(value, list):
        return any(unstorable(v) for v in value)
    if isinstance(value, dict):
        return any(unstorable(k) or unstorable(v) for k, v in value.items())
    return False


def lit(text):
    if TAG in text:
        sys.exit(f'{TAG} appears in a case')
    return f'{TAG}{text}{TAG}'


def jlit(value):
    return lit(json.dumps(value, ensure_ascii=False, sort_keys=False)) + '::jsonb'


def main():
    skips = load_skips()
    for spec, prefix, what in SPECS:
        files = sorted(p for p in (SUITE / prefix).glob('*.json'))
        groups, cases = [], []
        for path in files:
            name = prefix + path.name
            for group in json.loads(path.read_text()):
                gid = len(groups) + 1
                bad_schema = unstorable(group['schema'])
                groups.append(f"    ({gid}, {lit(name)}, {lit(group['description'])}, "
                              f"{'null' if bad_schema else jlit(group['schema'])})")
                for test in group['tests']:
                    reason = None
                    for key in ((name, group['description'], test['description']), (name, group['description'], '*'), (name, '*', '*')):
                        if key in skips:
                            reason = skips[key][0]
                            skips[key][1] += 1
                            break
                    if reason is None and (bad_schema or unstorable(test['data'])):
                        reason = 'U+0000 or an unpaired surrogate: not representable in Postgres jsonb'
                    data = 'null' if bad_schema or unstorable(test['data']) else jlit(test['data'])
                    cases.append(f"    ({gid}, {lit(test['description'])}, {data}, {str(test['valid']).lower()}, "
                                 f"{'null' if reason is None else lit(reason)})")
        out = [
            f'-- GENERATED by test/json_schema/generate.py from the JSON Schema Test Suite',
            f'-- (test/json_schema/upstream, commit {SOURCE}). Do not edit; edit skip.tsv and regenerate.',
            f'-- Goal: validate.json_schema() passes {what}.',
            '-- Skipped cases are listed in test/json_schema/skip.tsv with the reason.',
            'create temp table jsts_group (gid int primary key, file text, description text, schema jsonb);',
            'create temp table jsts_case (id serial, gid int, description text, data jsonb, valid boolean, skip text, got text);',
            '',
            'insert into jsts_group values',
            ',\n'.join(groups) + ';',
            '',
            'insert into jsts_case (gid, description, data, valid, skip) values',
            ',\n'.join(cases) + ';',
            '',
            r'\ir ../json_schema/run_suite.sql',
            '',
        ]
        (SPEC / spec).write_text('\n'.join(out))
        print(f'{spec}: {len(files)} files, {len(groups)} groups, {len(cases)} cases')
    unused = [k for k, (_, used) in skips.items() if not used]
    if unused:
        sys.exit('skip.tsv entries that match no case:\n' + '\n'.join('\t'.join(k) for k in unused))


main()
